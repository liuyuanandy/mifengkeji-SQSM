package com.beeinc.mylibrary.bean;

public class ARdata {
    private String kt;
    private String fs;

    public ARdata(String kt, String fs) {
        this.kt = kt;
        this.fs = fs;
    }

    public String getKt() {
        return this.kt;
    }

    public void setKt(String kt) {
        this.kt = kt;
    }

    public String getFs() {
        return this.fs;
    }

    public void setFs(String fs) {
        this.fs = fs;
    }
}
